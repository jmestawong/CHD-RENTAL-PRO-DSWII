DROP TABLE IF EXISTS pagos, mantenimientos, contratos, vehiculos, clientes, usuarios CASCADE;

CREATE TABLE usuarios (
    id_usuario       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo  VARCHAR(100) NOT NULL,
    email            VARCHAR(100) NOT NULL UNIQUE,
    password         VARCHAR(100) NOT NULL,              -- hash BCrypt ($2a$10$...)
    rol              VARCHAR(20)  NOT NULL CHECK (rol IN ('ADMIN','OPERADOR','PAGOS','GERENCIA')),
    telefono         VARCHAR(20),
    estado           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','INACTIVO')),
    fecha_creacion   TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    ultima_conexion  TIMESTAMP(6)
);

CREATE TABLE clientes (
    id_cliente        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razon_social      VARCHAR(150) NOT NULL,
    ruc               VARCHAR(11)  NOT NULL UNIQUE,
    direccion         VARCHAR(200),
    sector            VARCHAR(50),
    telefono          VARCHAR(20),
    email             VARCHAR(100),
    contacto_nombre   VARCHAR(100),
    contacto_cargo    VARCHAR(60),
    contacto_telefono VARCHAR(20),
    estado            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO','INACTIVO')),
    fecha_registro    TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    observaciones     VARCHAR(500)
);

CREATE TABLE vehiculos (
    id_vehiculo            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa                  VARCHAR(10)   NOT NULL UNIQUE,
    marca                  VARCHAR(50)   NOT NULL,
    modelo                 VARCHAR(50)   NOT NULL,
    anio                   INTEGER       NOT NULL,
    tipo                   VARCHAR(30),
    color                  VARCHAR(30),
    num_motor              VARCHAR(50),
    num_chasis             VARCHAR(50),
    capacidad_pasajeros    INTEGER,
    capacidad_carga        NUMERIC(10,2),
    kilometraje            INTEGER       NOT NULL DEFAULT 0,
    tarifa_diaria          NUMERIC(10,2) NOT NULL,
    estado                 VARCHAR(20)   NOT NULL DEFAULT 'DISPONIBLE'
                           CHECK (estado IN ('DISPONIBLE','ALQUILADO','MANTENIMIENTO','INACTIVO')),
    fecha_soat             DATE,
    fecha_revision_tecnica DATE,
    observaciones          VARCHAR(500),
    fecha_registro         TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE contratos (
    id_contrato         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_contrato     VARCHAR(20) UNIQUE,
    id_cliente          BIGINT NOT NULL REFERENCES clientes(id_cliente),
    id_vehiculo         BIGINT NOT NULL REFERENCES vehiculos(id_vehiculo),
    id_usuario          BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    fecha_inicio        DATE NOT NULL,
    fecha_fin           DATE NOT NULL,
    dias_alquiler       INTEGER NOT NULL,
    tarifa_diaria       NUMERIC(10,2) NOT NULL,
    subtotal            NUMERIC(12,2) NOT NULL,
    igv                 NUMERIC(12,2) NOT NULL,
    total               NUMERIC(12,2) NOT NULL,
    garantia            NUMERIC(12,2),
    kilometraje_inicial INTEGER,
    kilometraje_final   INTEGER,
    combustible_inicial VARCHAR(10),
    combustible_final   VARCHAR(10),
    estado              VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                        CHECK (estado IN ('PENDIENTE','ACTIVO','FINALIZADO','CANCELADO')),
    lugar_entrega       VARCHAR(200),
    lugar_devolucion    VARCHAR(200),
    observaciones       VARCHAR(500),
    fecha_creacion      TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_contrato_fechas CHECK (fecha_fin >= fecha_inicio)
);

CREATE TABLE pagos (
    id_pago            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contrato        BIGINT NOT NULL REFERENCES contratos(id_contrato),
    numero_comprobante VARCHAR(20) NOT NULL UNIQUE,
    tipo_comprobante   VARCHAR(20) NOT NULL CHECK (tipo_comprobante IN ('FACTURA','BOLETA','RECIBO')),
    fecha_pago         DATE NOT NULL,
    monto              NUMERIC(12,2) NOT NULL CHECK (monto > 0),
    metodo_pago        VARCHAR(20) NOT NULL
                       CHECK (metodo_pago IN ('EFECTIVO','TRANSFERENCIA','DEPOSITO','CHEQUE','TARJETA')),
    banco              VARCHAR(50),
    numero_operacion   VARCHAR(50),
    estado             VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADO' CHECK (estado IN ('PENDIENTE','CONFIRMADO','ANULADO')),
    observaciones      VARCHAR(500),
    fecha_registro     TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mantenimientos (
    id_mantenimiento      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_vehiculo           BIGINT NOT NULL REFERENCES vehiculos(id_vehiculo),
    tipo                  VARCHAR(20) NOT NULL CHECK (tipo IN ('PREVENTIVO','CORRECTIVO','REVISION')),
    fecha_inicio          DATE NOT NULL,
    fecha_fin             DATE,
    kilometraje           INTEGER,
    descripcion           VARCHAR(500) NOT NULL,
    taller                VARCHAR(100),
    costo                 NUMERIC(12,2),
    estado                VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO'
                          CHECK (estado IN ('PROGRAMADO','EN_PROCESO','COMPLETADO','CANCELADO')),
    proximo_mantenimiento DATE,
    observaciones         VARCHAR(500),
    fecha_registro        TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_contratos_vehiculo_fechas ON contratos (id_vehiculo, fecha_inicio, fecha_fin);
CREATE INDEX ix_pagos_contrato ON pagos (id_contrato);
CREATE INDEX ix_mantenimientos_vehiculo ON mantenimientos (id_vehiculo);

